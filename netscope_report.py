#!/usr/bin/env python3
"""Interactive, human-readable viewer for NetScope's Information history."""

from __future__ import annotations

import argparse
import json
import socket
import sys
import urllib.error
import urllib.parse
import urllib.request
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from netscope import resolve_target
from netscope_storage import CATEGORIES, load_records, save_record

CYAN = "\033[96m"
BLUE = "\033[94m"
GREEN = "\033[92m"
YELLOW = "\033[93m"
RED = "\033[91m"
DIM = "\033[2m"
RESET = "\033[0m"

DEFAULT_HEADERS = ("server", "content-type", "content-length", "location")


def paint(text: str, color: str) -> str:
    return f"{color}{text}{RESET}"


def build_report(target: str, timeout: float = 8.0) -> dict[str, Any]:
    """Collect a bounded DNS + HTTP report without launching a port scanner."""
    report: dict[str, Any] = {
        "tool": "NetScope CLI",
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "target": target,
        "dns": {},
        "http": {},
    }
    url = target if target.startswith(("http://", "https://")) else f"https://{target}"
    parsed = urllib.parse.urlparse(url)
    hostname = parsed.hostname or target
    try:
        address = resolve_target(hostname)
        aliases = socket.gethostbyname_ex(hostname)[1]
        report["dns"] = {"ipv4": address, "aliases": aliases}
    except (ValueError, socket.gaierror) as exc:
        report["dns"] = {"error": str(exc)}
        return report

    if not parsed.hostname:
        report["http"] = {"error": "URL does not contain a hostname."}
        return report
    request = urllib.request.Request(url, method="HEAD", headers={"User-Agent": "NetScope-Report/2.1"})
    try:
        with urllib.request.urlopen(request, timeout=timeout) as response:
            report["http"] = {
                "status": response.status,
                "reason": response.reason,
                "final_url": response.url,
                "headers": {key: response.headers.get(key) for key in DEFAULT_HEADERS if response.headers.get(key)},
            }
    except urllib.error.HTTPError as exc:
        report["http"] = {"status": exc.code, "reason": exc.reason, "final_url": exc.url}
    except (urllib.error.URLError, TimeoutError, ValueError) as exc:
        report["http"] = {"error": str(exc)}
    return report


def markdown_report(report: dict[str, Any]) -> str:
    dns = report["dns"]
    http = report["http"]
    lines = [
        "# NetScope Diagnostic Report",
        "",
        f"- **Target:** `{report['target']}`",
        f"- **Generated:** `{report['generated_at']}`",
        "",
        "## DNS",
        "",
        f"- **IPv4:** `{dns.get('ipv4', 'unavailable')}`",
        f"- **Aliases:** `{', '.join(dns.get('aliases', [])) or 'none'}`",
        "",
        "## HTTP",
        "",
    ]
    if "error" in http:
        lines.append(f"- **Error:** `{http['error']}`")
    else:
        lines.extend([
            f"- **Status:** `{http.get('status', 'unknown')} {http.get('reason', '')}`",
            f"- **Final URL:** `{http.get('final_url', 'unknown')}`",
        ])
        for key, value in http.get("headers", {}).items():
            lines.append(f"- **{key.title()}:** `{value}`")
    lines.extend(["", "> Generated by NetScope CLI. Use only for authorized diagnostics.", ""])
    return "\n".join(lines)


def print_readable(label: str, value: Any, indent: int = 0) -> None:
    """Render dict/list data as numbered text, never as raw braces or brackets."""
    prefix = " " * indent
    if isinstance(value, dict):
        if label:
            print(f"{prefix}{label}:")
        for key, child in value.items():
            print_readable(str(key), child, indent + 2)
    elif isinstance(value, list):
        if label:
            print(f"{prefix}{label}:")
        if not value:
            print(f"{' ' * (indent + 2)}(none)")
        for index, child in enumerate(value, 1):
            print(f"{' ' * (indent + 2)}{index}.")
            print_readable("", child, indent + 4)
    else:
        text = "(none)" if value in (None, "") else str(value)
        if "\n" in text:
            print(f"{prefix}{label}:")
            for line in text.splitlines():
                print(f"{' ' * (indent + 2)}{line}")
        else:
            print(f"{prefix}{label}: {text}")


def show_information(category: str, title: str) -> None:
    print(paint("\n" + "─" * 66, BLUE))
    print(paint(f"  {title}", CYAN))
    print(paint("─" * 66, BLUE))
    records = load_records(category)
    if not records:
        print(paint(f"No saved {category} information yet.", YELLOW))
        print(paint(f"Run the matching feature first; data will be saved to Information/{category}.json", DIM))
        return
    for index, record in enumerate(records, 1):
        print(paint(f"\n{index}.", GREEN))
        print_readable("", record, 2)


def report_menu() -> None:
    options = (
        ("1", "DNS lookup", "dns"),
        ("2", "All DNS addresses", "dns_addresses"),
        ("3", "Reverse DNS", "reverse_dns"),
        ("4", "HTTP headers", "http_headers"),
        ("5", "HTTP status & redirect", "http_status"),
        ("6", "TCP port check", "tcp"),
        ("7", "Common ports", "common_ports"),
        ("8", "Ping", "ping"),
        ("9", "Traceroute", "traceroute"),
        ("10", "TLS certificate", "tls"),
        ("11", "WHOIS", "whois"),
        ("12", "Local network", "local_network"),
        ("13", "Subnet calculator", "subnet"),
        ("14", "Nmap history", "nmap"),
        ("15", "Dependency history", "dependency"),
    )
    while True:
        print(paint("\n╔══════════════════════════════════════════════════════════════╗", CYAN))
        print(paint("║                 NETSCOPE REPORT VIEWER                    ║", CYAN))
        print(paint("╚══════════════════════════════════════════════════════════════╝", CYAN))
        for key, label, _ in options:
            print(f"  {key.rjust(2)}  {label}")
        print("  16  Credits & safety")
        print(paint("  17  Exit", RED))
        choice = input(paint("\nSelect option: ", GREEN)).strip()
        if choice == "17":
            print(paint("\nGoodbye.", CYAN))
            return
        if choice == "16":
            print("\ndeveloper: Wahyu Katnoko")
            print("co-developer: Echarina Bizulifah Putri")
            print(paint("Use reports only for systems you own or are authorized to inspect.", YELLOW))
        else:
            selected = next((item for item in options if item[0] == choice), None)
            if selected:
                show_information(selected[2], selected[1])
            else:
                print(paint("Unknown choice.", RED))
        input(paint("\nPress Enter to continue...", DIM))


def main() -> int:
    parser = argparse.ArgumentParser(description="View saved NetScope information or create a one-off report.")
    parser.add_argument("target", nargs="?", help="Optional hostname, IPv4 address, or URL for a one-off report")
    parser.add_argument("-o", "--output", type=Path, help="Output .json or .md for one-off mode")
    parser.add_argument("--timeout", type=float, default=8.0)
    args = parser.parse_args()
    if not args.target:
        report_menu()
        return 0
    if args.timeout <= 0 or args.timeout > 60:
        parser.error("--timeout must be between 0 and 60 seconds")
    report = build_report(args.target, args.timeout)
    save_record("dns", {"target": args.target, **report["dns"]})
    save_record("http", {"target": args.target, **report["http"]})
    if args.output:
        content = markdown_report(report) if args.output.suffix.lower() == ".md" else json.dumps(report, indent=2)
        args.output.write_text(content + "\n", encoding="utf-8")
        print(f"Report written to {args.output}")
    else:
        print(markdown_report(report))
    return 0


if __name__ == "__main__":
    sys.exit(main())
